// Regenerates src/lib/styles/primer-tokens.css from the installed @primer/primitives.
//
// The token list is derived from the `@theme inline` block in src/routes/layout.css:
// every var(--x) referenced there must exist in the Primer theme files (or in one of the
// functional :root imports, which are shipped as-is and not copied). Each theme token is
// copied together with its transitive var() closure, for light and dark, in the three
// selector blocks the app can reach (light+auto, dark, auto under prefers-color-scheme).
//
// Run after `pnpm up @primer/primitives`:  pnpm generate:tokens && pnpm test:e2e
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// fileURLToPath, not URL#pathname: pathname stays percent-encoded, which would break any
// checkout whose path contains spaces or non-ASCII characters (see generate-dictionary.mjs).
const root = fileURLToPath(new URL('..', import.meta.url));
const primitivesPkg = JSON.parse(
	readFileSync(`${root}node_modules/@primer/primitives/package.json`, 'utf8')
);
const layoutCss = readFileSync(`${root}src/routes/layout.css`, 'utf8');

// Functional :root files imported as-is by layout.css — their tokens need no copying.
const functionalFiles = [...layoutCss.matchAll(/@import '@primer\/primitives\/([^']+)';/g)]
	.map((m) => m[1])
	// Theme files are the ones we copy, not import.
	.filter((p) => !p.includes('/themes/'));

const themeFile = (name) =>
	readFileSync(
		`${root}node_modules/@primer/primitives/dist/css/functional/themes/${name}.css`,
		'utf8'
	);

// All `--x: value;` declarations in a CSS source (first occurrence wins).
function decls(src) {
	const map = new Map();
	const re = /(--[a-zA-Z0-9-]+)\s*:\s*([^;]+);/g;
	let m;
	while ((m = re.exec(src))) if (!map.has(m[1])) map.set(m[1], m[2].trim());
	return map;
}

const external = new Map(functionalFiles.flatMap((f) => [...decls(themelessRead(f))]));

function themelessRead(file) {
	return readFileSync(`${root}node_modules/@primer/primitives/${file}`, 'utf8');
}

// Top block = everything before the prefers-color-scheme media query.
function topBlock(src) {
	return src.slice(0, src.indexOf('@media (prefers-color-scheme: dark)'));
}

const lightDecl = decls(topBlock(themeFile('light')));
const darkDecl = decls(topBlock(themeFile('dark')));

// Seeds: var() references in the @theme inline block that the theme files own.
const themeBlock = layoutCss.match(/@theme inline \{([\s\S]*?)\n\}/)?.[1];
if (!themeBlock) throw new Error('no @theme inline block found in src/routes/layout.css');
const seeds = [
	...new Set(
		[...themeBlock.matchAll(/var\((--[a-zA-Z0-9-]+)/g)]
			.map((m) => m[1])
			.filter((name) => !external.has(name))
	)
];

// Print in seed order, expanding the transitive var() closure breadth-first.
// External references (functional imports) stay as var(); unknown tokens throw.
function body(decl) {
	const seen = new Set();
	const lines = [];
	const queue = [...seeds];
	while (queue.length) {
		const name = queue.shift();
		if (seen.has(name)) continue;
		seen.add(name);
		const value = decl.get(name);
		if (value === undefined) {
			throw new Error(
				`${name} is referenced from @theme but neither in the Primer theme files nor in the functional imports`
			);
		}
		lines.push(`\t${name}: ${value};`);
		for (const m of value.matchAll(/var\((--[a-zA-Z0-9-]+)/g)) {
			if (!external.has(m[1])) queue.push(m[1]);
		}
	}
	return lines.join('\n');
}

const out = `/*
 * Vendored color subset of @primer/primitives@${primitivesPkg.version} (https://github.com/primer/primitives).
 * GENERATED by scripts/generate-primer-tokens.mjs — do not edit by hand.
 * Source: dist/css/functional/themes/light.css and dark.css — only the tokens referenced
 * from @theme in src/routes/layout.css, plus their transitive var() closure. The full theme
 * files are an order of magnitude larger than this subset.
 * Regenerate after upgrading: pnpm generate:tokens && pnpm test:e2e
 *
 * Selector contract (see src/app.html): <html data-color-mode="light|dark|auto">.
 * "auto" follows the OS live via the trailing prefers-color-scheme block — do not reorder.
 */
[data-color-mode='light'],
[data-color-mode='auto'] {
${body(lightDecl)}
}

[data-color-mode='dark'] {
${body(darkDecl)}
}

@media (prefers-color-scheme: dark) {
	[data-color-mode='auto'] {
${body(darkDecl).replace(/^/gm, '\t')}
	}
}
`;
writeFileSync(`${root}src/lib/styles/primer-tokens.css`, out);
// Format in place so `pnpm lint` stays green right after regeneration (prettier.config.js is found via cwd).
execFileSync('prettier', ['--write', `${root}src/lib/styles/primer-tokens.css`], {
	cwd: root,
	stdio: 'inherit'
});
console.log(`primitives@${primitivesPkg.version}: wrote ${seeds.length} seeds`);
